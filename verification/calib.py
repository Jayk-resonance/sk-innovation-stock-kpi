rows = []
for ln in rows_txt.strip().splitlines():
    d, v, tv = ln.split()
    rows.append((d, int(v), int(tv)))
rows.sort()  # ascending by date

def vwap(start, end):
    sel = [r for r in rows if start <= r[0] <= end]
    tv = sum(r[2] for r in sel); v = sum(r[1] for r in sel)
    return tv / v, len(sel)

target = 113109
print(f"{'window':<24}{'days':>5}{'VWAP':>14}{'vs 113,109':>14}")
print("-"*57)
cands = [
    ("2M calendar 1031-1230", "20251031", "20251230"),
    ("2M calendar 1101-1230", "20251101", "20251230"),
    ("2M calendar 1030-1229", "20251030", "20251229"),
    ("1M calendar 1201-1230", "20251201", "20251230"),
    ("1M calendar 1130-1230", "20251130", "20251230"),
    ("1W 1222-1230",          "20251222", "20251230"),
    ("1W 1224-1230",          "20251224", "20251230"),
]
res = {}
for name, s, e in cands:
    w, n = vwap(s, e)
    res[name] = w
    print(f"{name:<24}{n:>5}{w:>14,.0f}{w-target:>14,.0f}")

